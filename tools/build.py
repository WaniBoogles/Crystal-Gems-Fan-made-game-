#!/usr/bin/env python3
"""
Crystal Gems! — single-file PC build.

Bundles src/game.html + src/game.css + src/game.js and every referenced image
(the seven lobby landscapes and the icons) into one portable, offline-friendly
Crystal-Gems.html at the repository root.

    python3 tools/build.py            # build
    python3 tools/build.py --check    # verify the bundle without writing it

No external tooling required — standard library only.
"""
from __future__ import annotations

import base64
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
OUT = ROOT / "Crystal-Gems.html"

MIME = {
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".svg": "image/svg+xml",
}


def data_uri(path: Path) -> str:
    payload = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{MIME.get(path.suffix.lower(), 'application/octet-stream')};base64,{payload}"


def inline_css(css: str) -> str:
    """Replace every url('relative-file') with an inline data URI."""

    def repl(match: re.Match[str]) -> str:
        rel = match.group(1)
        if rel.startswith(("data:", "http:", "https:")):
            return match.group(0)
        asset = (SRC / rel).resolve()
        if not asset.exists():
            raise FileNotFoundError(f"CSS references a missing asset: {rel}")
        return f"url('{data_uri(asset)}')"

    return re.sub(r"url\('([^')]+)'\)", repl, css)


def inline_icons(html: str) -> str:
    def repl(match: re.Match[str]) -> str:
        attr, rel = match.group(1), match.group(2)
        if rel.startswith(("data:", "http:", "https:", "#")):
            return match.group(0)
        asset = (SRC / rel).resolve()
        if not asset.exists():
            raise FileNotFoundError(f"HTML references a missing asset: {rel}")
        return f'{attr}="{data_uri(asset)}"'

    return re.sub(r'(href|src)="([^"]+\.(?:png|jpe?g|webp|svg))"', repl, html)


def build() -> str:
    html = (SRC / "game.html").read_text(encoding="utf-8")
    css = (SRC / "game.css").read_text(encoding="utf-8")
    js = (SRC / "game.js").read_text(encoding="utf-8")

    if 'href="game.css"' not in html or 'src="game.js"' not in html:
        raise RuntimeError("game.html no longer links game.css / game.js — update tools/build.py")

    css = inline_css(css)
    html = html.replace('<link rel="stylesheet" href="game.css">', f"<style>\n{css}\n</style>")
    # Optional pre-generated portrait data must be inlined before the game script.
    portraits_path = SRC / "portraits-data.js"
    if portraits_path.exists():
        portraits = portraits_path.read_text(encoding="utf-8")
        html = html.replace('<script src="portraits-data.js"></script>', f"<script>\n{portraits}\n</script>")

    html = html.replace('<script src="game.js"></script>', f"<script>\n{js}\n</script>")
    html = inline_icons(html)

    banner = (
        "<!--\n"
        "  Crystal Gems! — fan-made Steven Universe action battler\n"
        "  Single-file PC build. Generated by tools/build.py — edit src/ instead of this file.\n"
        "-->\n"
    )
    if html.startswith("<!DOCTYPE html>"):
        html = "<!DOCTYPE html>\n" + banner + html[len("<!DOCTYPE html>\n"):]
    else:
        html = banner + html

    return html


def main() -> int:
    try:
        html = build()
    except (FileNotFoundError, RuntimeError) as exc:
        print(f"BUILD FAILED: {exc}", file=sys.stderr)
        return 1

    problems = []
    if 'href="game.css"' in html:
        problems.append("stylesheet was not inlined")
    if 'src="game.js"' in html:
        problems.append("script was not inlined")
    if re.search(r"url\('(?!data:)[^']+\.(?:png|jpe?g|webp)'\)", html):
        problems.append("an image url() was left unresolved")
    if "manifest.json" in html:
        problems.append("manifest link still present (mobile packaging removed)")
    if problems:
        print("BUILD FAILED: " + "; ".join(problems), file=sys.stderr)
        return 1

    if "--check" in sys.argv:
        print(f"Bundle OK — {len(html) / 1024 / 1024:.2f} MB, no external assets.")
        return 0

    OUT.write_text(html, encoding="utf-8")
    print(f"Built {OUT.relative_to(ROOT)} — {len(html) / 1024 / 1024:.2f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
